#!/usr/bin/env bash
# 生成 Arch Linux 包：logseq-<version>-<rel>-loong64.pkg.tar.zst
# 优先用 makepkg；系统无 makepkg 时，用 bsdtar + zstd 按等价 PKGBUILD 逻辑手工构造。
set -euo pipefail
cd "$(dirname "$0")/../.."

UNPACKED=static/dist/linux-unpacked
[ -d "$UNPACKED" ] || { echo "缺少 $UNPACKED，请先运行 build.sh"; exit 1; }
VERSION=$(node -p "require('./static/package.json').version")
REL=${PKGREL:-1}
WORK=static/dist/pkgbuild
OUT=static/dist
PKGNAME="logseq-$VERSION-$REL-loong64.pkg.tar.zst"

rm -rf "$WORK"
mkdir -p "$WORK"
cp -a "$UNPACKED" "$WORK/linux-unpacked"
cp static/icons/logseq.png "$WORK/logseq.png"

DEPS=('gtk3' 'nss' 'libxss' 'libxtst' 'alsa-lib' 'libsecret' 'libnotify' 'libxkbcommon' 'mesa')

make_pkgdir() {
  local root=$1
  install -d "$root/opt/Logseq" "$root/usr/bin" "$root/usr/share/applications" \
    "$root/usr/share/icons/hicolor/512x512/apps" "$root/usr/share/pixmaps"
  cp -a "$UNPACKED/." "$root/opt/Logseq/"
  ln -sf /opt/Logseq/logseq "$root/usr/bin/logseq"
  install -Dm644 "$WORK/logseq.png" "$root/usr/share/icons/hicolor/512x512/apps/logseq.png"
  install -Dm644 "$WORK/logseq.png" "$root/usr/share/pixmaps/logseq.png"
  cat > "$root/usr/share/applications/logseq.desktop" <<'DESK'
[Desktop Entry]
Name=Logseq
Comment=A privacy-first, open-source platform for knowledge management
Type=Application
Categories=Office;
Exec=logseq %U
Icon=logseq
Terminal=false
StartupWMClass=Logseq
MimeType=x-scheme-handler/logseq;
DESK
}

if command -v makepkg >/dev/null 2>&1; then
  echo "=== 使用 makepkg 打包 ==="
  cat > "$WORK/PKGBUILD" <<EOF
pkgname=logseq
pkgver=$VERSION
pkgrel=$REL
pkgdesc="Privacy-first, open-source platform for knowledge management"
arch=('loong64')
url="https://logseq.com"
license=('AGPL-3.0')
depends=($(printf "'%s' " "${DEPS[@]}"))
options=('!strip' '!debug')

package() {
  install -d "\$pkgdir/opt/Logseq" "\$pkgdir/usr/bin" "\$pkgdir/usr/share/applications"
  cp -a "\$startdir/linux-unpacked/." "\$pkgdir/opt/Logseq/"
  ln -sf /opt/Logseq/logseq "\$pkgdir/usr/bin/logseq"
  install -Dm644 "\$startdir/logseq.png" "\$pkgdir/usr/share/icons/hicolor/512x512/apps/logseq.png"
  install -Dm644 "\$startdir/logseq.png" "\$pkgdir/usr/share/pixmaps/logseq.png"
  install -Dm644 /dev/stdin "\$pkgdir/usr/share/applications/logseq.desktop" <<'DESK'
[Desktop Entry]
Name=Logseq
Comment=A privacy-first, open-source platform for knowledge management
Type=Application
Categories=Office;
Exec=logseq %U
Icon=logseq
Terminal=false
StartupWMClass=Logseq
MimeType=x-scheme-handler/logseq;
DESK
}
EOF
  CONF_ARGS=()
  [ -n "${MAKEPKG_CONF:-}" ] && CONF_ARGS=(--config "$MAKEPKG_CONF")
  (cd "$WORK" && makepkg -A -f --nodeps --nocheck "${CONF_ARGS[@]}")
  mv "$WORK/$PKGNAME" "$OUT/"
else
  echo "=== makepkg 不可用，用 bsdtar + zstd 手工构造 Arch 包 ==="
  command -v bsdtar >/dev/null 2>&1 || { echo "缺少 bsdtar（libarchive-tools）" >&2; exit 1; }
  command -v zstd   >/dev/null 2>&1 || { echo "缺少 zstd" >&2; exit 1; }
  ROOT="$WORK/pkg"
  make_pkgdir "$ROOT"

  INSTALLED_SIZE=$(du -sb "$ROOT/opt" "$ROOT/usr" | awk '{s+=$1} END{print s}')
  BUILDDATE=$(date +%s)
  PACKAGER="${PACKAGER:-acdcGGE <hello@logseq.com>}"

  # .PKGINFO：pacman 安装所需的最小元数据，字段顺序与 makepkg 一致
  {
    echo "# Generated by scripts/loong64/pkg.sh (manual mode)"
    echo "# using bsdtar + zstd on loong64"
    echo "pkgname = logseq"
    echo "pkgver = $VERSION-$REL"
    echo "pkgdesc = Privacy-first, open-source platform for knowledge management"
    echo "url = https://logseq.com"
    echo "builddate = $BUILDDATE"
    echo "packager = $PACKAGER"
    echo "size = $INSTALLED_SIZE"
    echo "arch = loong64"
    echo "license = AGPL-3.0"
    for d in "${DEPS[@]}"; do echo "depend = $d"; done
  } > "$ROOT/.PKGINFO"

  # .MTREE：先在包外生成，避免把自身算进去；选项与 makepkg 默认一致
  MTREE_TMP="$(cd "$WORK" && pwd)/.MTREE"
  (cd "$ROOT" && bsdtar -cf "$MTREE_TMP" --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,sha256,link' .)
  mv "$MTREE_TMP" "$ROOT/.MTREE"

  cat > "$ROOT/.BUILDINFO" <<EOF
# Generated by scripts/loong64/pkg.sh (manual mode)
format = 2
pkgname = logseq
pkgver = $VERSION-$REL
pkgarch = loong64
pkgbuild_sha256 = unsigned
packager = $PACKAGER
builddate = $BUILDDATE
builddir = /build
EOF

  rm -f "$OUT/$PKGNAME"
  (cd "$ROOT" && bsdtar -cf - .PKGINFO .MTREE .BUILDINFO opt usr) | \
    zstd -q -T0 -15 -o "$OUT/$PKGNAME"
fi

ls -lh "$OUT/$PKGNAME"
